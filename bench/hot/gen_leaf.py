#!/usr/bin/env python3
"""Generate a large leaf crate for PLIRON_HOT scaling tests.

Usage: gen_leaf.py OUT N [SEED]
Deterministic: same N and SEED give the same file. `probe()` returns a
constant the hot harness edits; `total()` sums every function so each
tick exercises all thunk slots.
"""
import random
import sys

out, n = sys.argv[1], int(sys.argv[2])
rng = random.Random(int(sys.argv[3]) if len(sys.argv) > 3 else 7)

fns = []
for i in range(n):
    a, b, k = rng.getrandbits(32), rng.getrandbits(32), rng.randrange(1, 32)
    body = f"x.wrapping_mul(0x{a:08x}).rotate_right({k}) ^ 0x{b:08x}"
    if i and rng.random() < 0.25:
        body = f"({body}).wrapping_add(f{i - 1:05}(x))"
    fns.append(f"#[inline(never)]\npub fn f{i:05}(x: u64) -> u64 {{ {body} }}")

stmts = " ".join(f"s = s.wrapping_add(f{i:05}(x));" for i in range(n))
open(out, "w").write(f"""// generated by bench/hot/gen_leaf.py — do not edit
use std::sync::atomic::{{AtomicU64, Ordering}};

pub static COUNTER: AtomicU64 = AtomicU64::new(0);
pub static NAME: [u8; 8] = *b"hot-leaf";

{chr(10).join(fns)}

#[inline(never)]
pub fn probe(_x: u64) -> u64 {{
    // HOT_EDIT marker: the harness rewrites this body.
    1
}}

#[inline(never)]
pub fn counter_bump() -> u64 {{
    COUNTER.fetch_add(1, Ordering::Relaxed)
}}

#[inline(never)]
pub fn total(x: u64) -> u64 {{
    let mut s = 0u64;
    {stmts}
    s
}}
""")
