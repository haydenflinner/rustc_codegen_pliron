#!/usr/bin/env -S python3 -I
"""Round-trip (edit -> build -> link) parity: stock rustc vs pliron.

Usage: harness/rtt.py [--runs N] [--only thin|large] [--json OUT]
                      [--linker LD] [--debug-dylib]

Shape: a thin bin (~20 lines of egui/wgpu/winit calls) and a generated
~12 kLOC bin (1200 live fns) over a 281-crate egui+wgpu+winit tree in
bench/rtt — the "GUI app, edit one widget" loop. Deps build once per
backend; each rep edits the leaf and times `cargo build`.

A rep = one source edit + `cargo build`. Thin edits append a marker
comment (real relink, no new codegen — the floor). Large edits change
a seed inside worker_500 (one CGU of real codegen + relink).

--linker LD passes -Clinker=LD for the pliron side only (e.g. the
incremental linker tools/pliron-inc-ld); stock keeps its default.

Results: table + target/parity/rtt.json. Per-rep rustc breakdown:
cargo rustc --bin rtt -- -Ztime-passes inside bench/rtt.
See docs/PARITY.md, docs/history/2026-11-06-round-trip-parity.md.
"""
import argparse, json, os, re, statistics, subprocess, sys, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJ = os.path.join(ROOT, "bench", "rtt")
SO = {"darwin": "dylib", "win32": "dll"}.get(sys.platform, "so")
LIB = "" if sys.platform == "win32" else "lib"
TOOLCHAIN = open(os.path.join(ROOT, "rust-toolchain.toml")).read().split('channel = "')[1].split('"')[0]

LARGE = """// Generated by harness/rtt.py: ~12 kLOC, 1200 live functions over the
// same dep stack — the "everything in one crate" shape.
{workers}
fn main() {{
    let tab: [fn(u64) -> u64; 1200] = [{fns}];
    let mut h = 0u64;
    for (i, f) in tab.iter().enumerate() {{ h ^= f(h.wrapping_add(i as u64)); }}
    let _ev: Option<winit::event::Event<()>> = None;
    let _attrs = wgpu::RequestAdapterOptions::default();
    println!("large leaf {{h}}");
}}
"""


def gen_large():
    path = os.path.join(PROJ, "src", "bin", "large.rs")
    if os.path.exists(path):
        return
    ws = []
    for i in range(1200):
        ws.append(f"""#[inline(never)]
fn worker_{i}(x: u64) -> u64 {{
    let mut acc = x ^ {i};
    for j in 0..(x % 97 + {i % 13}) {{
        acc = acc.wrapping_mul(0x9e3779b97f4a7c15).wrapping_add(j);
        acc ^= acc >> 29;
    }}
    egui::Color32::from_rgb((acc & 0xff) as u8, ((acc>>8)&0xff) as u8, ((acc>>16)&0xff) as u8);
    acc
}}""")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(LARGE.format(workers="\n".join(ws),
                                      fns=", ".join(f"worker_{i}" for i in range(1200))))


def edit_thin(n):
    with open(os.path.join(PROJ, "src", "main.rs"), "a") as f:
        f.write(f"// rtt-{n}\n")


def edit_large(n):
    p = os.path.join(PROJ, "src", "bin", "large.rs")
    s = open(p).read()
    d = int(re.sub(r"\D", "", n) or "0")
    s = re.sub(r"(fn worker_500\(x: u64\) -> u64 \{\n    let mut acc = x \^ )\d+",
               rf"\g<1>{d}9{d}", s, count=1)
    open(p, "w").write(s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=5)
    ap.add_argument("--only", default="thin,large")
    ap.add_argument("--json", default=os.path.join(ROOT, "target", "parity", "rtt.json"))
    ap.add_argument("--linker", default=None)
    ap.add_argument("--debug-dylib", action="store_true")
    a = ap.parse_args()

    gen_large()
    prof = "debug" if a.debug_dylib else "release"
    dylib = os.path.join(ROOT, "target", prof, f"{LIB}rustc_codegen_pliron.{SO}")
    if not os.path.exists(dylib):
        sys.exit(f"build the backend first: cargo build --{prof}")

    env0 = dict(os.environ, RUSTUP_TOOLCHAIN=TOOLCHAIN, RUSTC_BOOTSTRAP="1")
    sides = {
        "stock": dict(env0, CARGO_TARGET_DIR=os.path.join(ROOT, "target", "rtt-stock"),
                      RUSTFLAGS=""),
        "pliron": dict(env0, CARGO_TARGET_DIR=os.path.join(ROOT, "target", "rtt-pliron"),
                       RUSTFLAGS=f"-Zcodegen-backend={dylib}"),
    }
    if a.linker:
        sides["incld"] = dict(
            env0,
            CARGO_TARGET_DIR=os.path.join(ROOT, "target", "rtt-incld"),
            RUSTFLAGS=f"-Zcodegen-backend={dylib} -Clinker={a.linker}",
        )

    def build(side, binc):
        t0 = time.time()
        r = subprocess.run(["cargo", "build", "--offline", "--bin", binc, "-q"],
                           cwd=PROJ, env=sides[side], capture_output=True, text=True)
        return time.time() - t0, r

    shapes = {"thin": ("rtt", edit_thin), "large": ("large", edit_large)}
    res = {}
    for name in a.only.split(","):
        binc, edit = shapes[name]
        for side in sides:
            t, r = build(side, binc)
            if r.returncode:
                sys.exit(f"{side} cold build failed:\n{r.stderr[-3000:]}")
        for i in range(a.runs):
            for side in sides:
                edit(f"{name}-{side}-{i}")
                t, r = build(side, binc)
                if r.returncode:
                    sys.exit(f"{side} incremental build failed:\n{r.stderr[-3000:]}")
                res.setdefault(side, {})[name] = res.get(side, {}).get(name, []) + [round(t, 3)]

    print(f"{'shape':<10}{'side':<9}{'median':>8}  all reps")
    out = {}
    for side, shapes in res.items():
        for name, ts in shapes.items():
            med = statistics.median(ts[1:] if len(ts) > 2 else ts)  # skip warmup
            out.setdefault(side, {})[name] = {"median": med, "runs": ts}
            print(f"{name:<10}{side:<9}{med:>7.3f}s  {ts}")
    for side in out:
        if side == "stock":
            continue
        for name in out.get("stock", {}):
            if name in out[side]:
                r = out[side][name]["median"] / out["stock"][name]["median"]
                print(f"  {name} ratio {side}/stock = {r:.3f}")
    os.makedirs(os.path.dirname(a.json), exist_ok=True)
    json.dump(out, open(a.json, "w"), indent=1)
    print(f"wrote {a.json}")


if __name__ == "__main__":
    main()
